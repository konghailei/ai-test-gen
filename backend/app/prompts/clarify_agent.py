def build_user_prompt(
    srr: dict,
    kb_inferred_fields: list[dict] | None = None,
    similar_reqs: list[dict] | None = None,
    completeness: dict | None = None,
    ambiguities: list | None = None,
) -> str:
    """构建 ClarifyAgent 的用户指令。

    Args:
        srr: SRR JSON 字典
        kb_inferred_fields: KB 已自动补全的字段列表（这些不再生成问题），
            每项含 {field, value, similarity, source_req_id}
        similar_reqs: 同类历史需求列表（用于遗漏检测对比），
            每项含 {title, dimensions（缺失维度参考）}
        completeness: _check_completeness + PRD 专项检测的结果（包含 prd_missing / prd_ambiguities）
        ambiguities: _detect_ambiguity + PRD专项检测的歧义列表

    Returns:
        str: 完整的用户指令

    Note:
        - 将 KB 已补全的字段告知 LLM，避免重复提问
        - 将同类需求的维度列表注入，辅助遗漏检测
        - v2.8.64: 将 PRD 专项检测的结果（prd_missing/prd_ambiguities）注入，
          防止 LLM 对 PRD 类文档给出 overall=1.0 的满分（明明规则层已检测出缺口）
    """
    kb_hint = ""
    if kb_inferred_fields:
        kb_hint = f"""

【KB 已自动补全的字段（无需再问人工）】
{json.dumps(kb_inferred_fields, ensure_ascii=False, indent=2)}"""

    similar_hint = ""
    if similar_reqs:
        similar_hint = f"""

【同类历史需求参考（用于遗漏检测）】
{json.dumps(similar_reqs, ensure_ascii=False, indent=2)}"""

    # v2.8.63: 如果 SRR 中包含 _raw_text，增加引用未定义检测提醒
    # 这不是正则预扫描，只是通用提醒，引导 LLM 重点关注引用未定义
    reference_check_hint = ""
    if srr.get("_raw_text"):
        reference_check_hint = """

⚠️ 检测重点提醒（v2.8.63）：
原始需求文档可能包含"引用了某规则但未定义具体内容"的表述（如"与现有XX一致""沿用现有XX""按现有XX执行"等）。
请务必逐一检查文档中所有验收标准和业务规则，判断是否存在引用了外部规则但文档通篇未定义该规则具体内容的情况。
关键判断：关键词出现 ≠ 规则已定义——即使文档多次提到"图片上传"，只要没有列出具体支持的格式和大小限制，就视为引用未定义。
检测到则生成 ambiguity 问题（category=ambiguity），询问该规则的具体内容。"""

    # v2.8.64: 注入 PRD 专项检测结果（规则层已发现的缺口）。
    # 如果 completeness 中包含 prd_missing 或 prd_ambiguities，就明确告诉 LLM：
    # 「规则层已经检测到以下 X 个缺口和 Y 个歧义，请你不要给满分，请逐条验证并生成澄清问题」
    prd_rule_hint = ""
    if completeness:
        prd_missing = completeness.get("prd_missing") or []
        prd_amb = completeness.get("prd_ambiguities") or []
        if prd_missing or prd_amb:
            hint_parts = [f"\n\n⚠️ 检测重点提醒（v2.8.64 PRD 专项检测结果 — 请逐条验证，不得对这些缺口给满分 overall=1.0）："]
            if prd_missing:
                hint_parts.append(f"\n【规则层检测到的语义遗漏 / 能力缺口（共 {len(prd_missing)} 项，请逐条验证是否真的缺失，若缺失则生成对应 gap 问题）：")
                for i, m in enumerate(prd_missing, 1):
                    ev = str(m.get("evidence", ""))[:150]
                    sq = str(m.get("_suggested_question") or m.get("suggested_question", ""))[:200]
                    so = m.get("_suggested_options") or m.get("suggested_options") or []
                    opts_str = f"，建议候选选项: {so}" if so else ""
                    hint_parts.append(
                        f"  {i}. field={m.get('field','?')} / {m.get('category','gap')}\n"
                        f"     描述: {m.get('description','')[:150]}\n"
                        f"     证据: {ev}\n"
                        f"     建议问句: {sq}{opts_str}"
                    )
            if prd_amb:
                hint_parts.append(f"\n【规则层检测到的歧义 / 立场不一致（共 {len(prd_amb)} 项，请逐条验证是否真的不一致，若存在则生成对应 ambiguity/conflict 问题）：】")
                for i, a in enumerate(prd_amb, 1):
                    ev = str(a.get("evidence", ""))[:180]
                    sq = str(a.get("_suggested_question") or a.get("suggested_question", ""))[:200]
                    so = a.get("_suggested_options") or a.get("suggested_options") or []
                    opts_str = f"，建议候选选项: {so}" if so else ""
                    hint_parts.append(
                        f"  {i}. field={a.get('field','?')} / {a.get('category','ambiguity')}\n"
                        f"     描述: {a.get('description','')[:150]}\n"
                        f"     证据: {ev}\n"
                        f"     建议问句: {sq}{opts_str}"
                    )
            hint_parts.append(
                "\n重要：对以上规则层检测到的缺口，请你逐一验证原文——如果确认存在，就必须生成对应的澄清问题，"
                "不得跳过。如果确认文档中确实已经有对应内容，请在 issues_detected 中标记为 rule_false_positive，"
                "但不得给 overall_score=1.0 满分（存在争议即说明有澄清必要）。"
            )
            prd_rule_hint = "\n".join(hint_parts)

    # v3.1.6: 注入常规规则缺口清单（critical/important missing）——配合 SYSTEM_PROMPT
    # 的「【规则检测缺口】清单优先处理」要求。PRD 专项缺口已在 prd_rule_hint 展示，
    # 此处按 field 去重避免重复。
    rule_gap_hint = ""
    if completeness:
        _gap_items = (completeness.get("critical_missing") or []) + (completeness.get("important_missing") or [])
        _prd_fields = {str(m.get("field", "")) for m in (completeness.get("prd_missing") or []) if isinstance(m, dict)}
        _gap_items = [g for g in _gap_items if isinstance(g, dict) and str(g.get("field", "")) not in _prd_fields]
        if _gap_items:
            _rg_parts = [
                f"\n\n⚠️ 规则检测缺失字段清单（共 {len(_gap_items)} 项 — 请优先逐项处理："
                f"确认缺失则生成对应 question 条目；若你判断原文已覆盖（清单误报）可不生成人工问题，"
                f"系统会用兜底 KB 查询自动核对该项）："
            ]
            for i, g in enumerate(_gap_items, 1):
                sq = str(g.get("_suggested_question") or g.get("suggested_question", ""))[:200]
                so = g.get("_suggested_options") or g.get("suggested_options") or []
                opts_str = f"，建议候选选项: {so}" if so else ""
                _rg_parts.append(
                    f"  {i}. field={g.get('field','?')} / priority={g.get('priority','?')}\n"
                    f"     描述: {str(g.get('description',''))[:150]}\n"
                    f"     建议问句: {sq}{opts_str}"
                )
            rule_gap_hint = "\n".join(_rg_parts)

    # v2.8.64: 注入规则层检测到的歧义 / 跨文档矛盾候选线索（ambiguities）。
    # 主要目的：让 LLM 明确知道「这是一个多文档上传场景」，重点排查跨文档矛盾；
    # 同时将跨文档同名词候选列表展示给 LLM，作为重点排查线索。
    cross_doc_hint = ""
    if ambiguities:
        cross = [a for a in ambiguities if isinstance(a, dict) and str(a.get("type", "")).startswith("cross_doc_")]
        if cross:
            cd_parts = [f"\n\n⚠️ 检测重点提醒（v2.8.64 跨文档矛盾预检测 — 请对以下候选逐条做语义判断）："]
            # 找出候选中涉及的文档名
            docs_mentioned: list[str] = []
            raw = srr.get("_raw_text", "") or ""
            import re
            dm = re.findall(r"【文档：([^】]+)】", raw)
            if len(dm) >= 2:
                docs_mentioned = dm
            cd_parts.append(f"\n【场景说明】本次上传为多文档场景，共涉及 {len(docs_mentioned)} 个文档：" + "、".join(docs_mentioned))
            cd_parts.append("请重点核对：同一名词/规则/阈值/角色权限在不同文档中是否定义不一致？同一名词在不同文档中表达不同含义？")
            cd_parts.append(f"\n【规则层检测到的跨文档矛盾候选（共 {len(cross)} 项，请逐条做语义验证，不一致则生成 conflict 问题）：】")
            for i, a in enumerate(cross, 1):
                ev = str(a.get("evidence", ""))[:180]
                sq = str(a.get("_suggested_question") or a.get("suggested_question", ""))[:250]
                so = a.get("_suggested_options") or a.get("suggested_options") or []
                opts_str = f"，建议候选选项: {so}" if so else ""
                cd_parts.append(
                    f"  {i}. type={a.get('type','?')} / field={a.get('field','?')}\n"
                    f"     描述: {str(a.get('description',''))[:200]}\n"
                    f"     证据: {ev}\n"
                    f"     建议问句: {sq}{opts_str}"
                )
            cd_parts.append(
                "\n重要：以上仅为规则层预扫描出的候选（可能存在误报，需你结合语义验证）。"
                "除了这些候选，请你主动对 _raw_text 中不同【文档：XXX】片段之间的所有名词、规则、"
                "阈值、角色定义做全文交叉比对，凡发现语义矛盾的都要生成 conflict 类澄清问题。"
                "不得因为候选中没有就跳过跨文档矛盾全文扫描。"
            )
            cross_doc_hint = "\n".join(cd_parts)

    # P3-8 提示注入防御：srr 携带的 _raw_text 是不可信外部内容，包裹后再注入
    if srr.get("_raw_text"):
        from app.utils.external_content import wrap_external_content
        srr = {**srr, "_raw_text": wrap_external_content(str(srr["_raw_text"]))}
    return f"""请对以下需求（含初步结构化草稿）进行三级检测（完整性/歧义性/遗漏），识别会阻碍生成完整 SRR 的缺口与模糊点，并生成人工澄清问题列表。

{QUESTIONS_SCHEMA}
{kb_hint}
{similar_hint}
{reference_check_hint}
{prd_rule_hint}
{rule_gap_hint}
{cross_doc_hint}

【待分析的需求与初步草稿】
{json.dumps(srr, ensure_ascii=False, indent=2)}

请直接输出检测结果 JSON，不要包含其他解释性文字。"""


